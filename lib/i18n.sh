# shellcheck shell=bash
# UI localization. English is the source language and the default language.
#
# Static UI strings are translated automatically by the ui_* helpers through
# i18n_text(). Messages with variables use T 'format %s' "$value" so the
# translation catalogue can keep the printf placeholders in the right order.

GI_LANG="${GI_LANG:-en}"
I18N_LANG="${GI_LANG}"
GI_UI_LOCALE=""
GI_I18N_LOADED=0
declare -A I18N_RU=()

i18n_dir() {
    local dir
    dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
    printf '%s' "$dir"
}

i18n_missing() {
    local text=$1
    [[ ${GI_I18N_DEBUG:-0} == 1 ]] || return 0
    [[ -n ${GI_LOG_FILE:-} ]] || return 0
    printf '%s [WARN ] i18n missing ru: %s\n' \
        "$(date -u '+%Y-%m-%d %H:%M:%S')" "$text" >>"$GI_LOG_FILE" 2>/dev/null || true
}

i18n_load_catalog() {
    ((GI_I18N_LOADED)) && return 0
    local file en ru
    file="$(i18n_dir)/lang/ru.tsv"
    if [[ -r $file ]]; then
        while IFS=$'\t' read -r en ru || [[ -n ${en:-} ]]; do
            [[ -z $en || $en == \#* ]] && continue
            en=$(printf '%b' "$en")
            ru=$(printf '%b' "$ru")
            I18N_RU["$en"]=$ru
        done <"$file"
    fi
    GI_I18N_LOADED=1
}

i18n_init() {
    local lang=${1:-${GI_LANG:-en}}
    case "$lang" in
        en|ru) ;;
        *) lang=en ;;
    esac
    GI_LANG=$lang
    I18N_LANG=$lang
    i18n_load_catalog
    i18n_apply_locale "$lang"
}

# Translate a complete, already-built string. Only exact catalogue entries are
# translated; values supplied by the user are never rewritten.
i18n_text() {
    local text=${1:-}
    if [[ ${I18N_LANG:-en} == ru && -n $text ]]; then
        if [[ -n ${I18N_RU[$text]+set} ]]; then
            printf '%s' "${I18N_RU[$text]}"
            return 0
        fi
        i18n_missing "$text"
    fi
    printf '%s' "$text"
}

# Translate a printf format and apply its arguments. Args are data, never a
# format string, so values containing % are safe.
i18n_format() {
    local key=$1 out
    shift
    local fmt=$key
    if [[ ${I18N_LANG:-en} == ru ]]; then
        if [[ -n ${I18N_RU[$key]+set} ]]; then
            fmt=${I18N_RU[$key]}
        else
            i18n_missing "$key"
        fi
    fi
    if (($# == 0)); then
        printf '%s' "$fmt"
        return 0
    fi
    # shellcheck disable=SC2059
    printf -v out "$fmt" "$@"
    printf '%s' "$out"
}

T() { i18n_format "$@"; }

i18n_available_locales() {
    if [[ -n ${GI_LOCALE_LIST:-} ]]; then
        printf '%s\n' "$GI_LOCALE_LIST"
    else
        locale -a 2>/dev/null || true
    fi
}

i18n_has_locale() {
    local wanted=$1 alt
    alt="${wanted%.UTF-8}.utf8"
    i18n_available_locales | grep -Fxiq -- "$wanted" && return 0
    i18n_available_locales | grep -Fxiq -- "$alt" && return 0
    return 1
}

i18n_generate_locale() {
    local lang=$1
    command_exists localedef || return 1
    case "$lang" in
        ru) localedef -i ru_RU -f UTF-8 ru_RU.UTF-8 >/dev/null 2>&1 || return 1 ;;
        en) localedef -i en_US -f UTF-8 en_US.UTF-8 >/dev/null 2>&1 || return 1 ;;
        *) return 1 ;;
    esac
}

i18n_locale_for() {
    local lang=$1
    case "$lang" in
        ru)
            if i18n_has_locale ru_RU.UTF-8 || i18n_generate_locale ru; then
                printf 'ru_RU.UTF-8'
                return 0
            fi
            ;;
    esac
    if i18n_has_locale C.UTF-8; then
        printf 'C.UTF-8'
    elif i18n_has_locale en_US.UTF-8; then
        printf 'en_US.UTF-8'
    elif i18n_has_locale C.utf8; then
        printf 'C.utf8'
    else
        printf 'C'
    fi
}

# Set a UTF-8 environment for the TUI. Russian is preferred when it is
# available (or can be generated by localedef), otherwise C.UTF-8 keeps the
# Unicode box drawing and Cyrillic labels intact.
i18n_apply_locale() {
    local lang=$1 name
    name=$(i18n_locale_for "$lang")
    GI_UI_LOCALE=$name
    export LANG="$name"
    export LC_ALL="$name"
}

i18n_language_label() {
    case "$1" in
        ru) printf 'Русский' ;;
        *) printf 'English' ;;
    esac
}

i18n_choose_language() {
    local default=${CFG_UI_LANGUAGE:-${GI_LANG:-en}} choice old_locale=${CFG_LOCALE:-}
    ui_menu "Language / Язык" \
        "Choose the installer language. / Выберите язык установщика." "$default" \
        "en|English|English interface" \
        "ru|Русский|Русский интерфейс" || return 0
    choice=$UI_RESULT
    case "$choice" in
        en|ru) ;;
        *) return 0 ;;
    esac
    CFG_UI_LANGUAGE=$choice
    i18n_init "$choice"
    # A Russian UI is normally paired with a Russian target locale. Only adjust
    # the target locale when it was still the previous language default; an
    # explicit user choice is preserved.
    if [[ $choice == ru && $old_locale == en_US.UTF-8 ]]; then
        CFG_LOCALE=ru_RU.UTF-8
    elif [[ $choice == en && $old_locale == ru_RU.UTF-8 ]]; then
        CFG_LOCALE=en_US.UTF-8
    fi
    config_derived
    config_save
}

i18n_load_catalog
