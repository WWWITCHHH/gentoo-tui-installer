# shellcheck shell=bash
# Kernel installation: binary, distribution or manual gentoo-sources.

kernel_extra_cmdline() {
    printf '%s' "$CFG_KERNEL_CMDLINE" |
        sed -E 's/(^|[[:space:]])root=[^[:space:]]*//g; s/^[[:space:]]+//; s/[[:space:]]+$//'
}

kernel_write_cmdline() {
    local extra dir="$GI_ROOT/etc/kernel"
    extra=$(kernel_extra_cmdline)
    ensure_dir "$dir"
    {
        printf 'root=UUID=%s ro' "$CFG_UUID_ROOT"
        [[ -n $extra ]] && printf ' %s' "$extra"
        printf '\n'
    } | write_file_atomic "$dir/cmdline" 0644
    log_info "kernel cmdline written: root=UUID=$CFG_UUID_ROOT ro $extra"
}

kernel_write_dracut_conf() {
    local dir="$GI_ROOT/etc/dracut.conf.d"
    ensure_dir "$dir"
    {
        printf '# Generated by %s %s\n' "$GI_NAME" "$GI_VERSION"
        printf '# Do not inherit the live CD kernel command line or hardware set.\n'
        printf 'hostonly="no"\n'
        printf 'hostonly_cmdline="no"\n'
    } | write_file_atomic "$dir/99-installer.conf" 0644
    log_info "dracut configuration written (hostonly=no, hostonly_cmdline=no)"
}

kernel_cpu_vendor() {
    local vendor
    vendor=$(awk -F: '/^vendor_id/ {gsub(/^[ \t]+|[ \t]+$/, "", $2); print $2; exit}' /proc/cpuinfo 2>/dev/null || true)
    case "$vendor" in
        GenuineIntel) printf 'intel' ;;
        AuthenticAMD) printf 'amd' ;;
        *) printf 'unknown' ;;
    esac
}

kernel_install_initramfs_tools() {
    chroot_run "$(T 'Installing installkernel and dracut')" \
        emerge --ask=n --quiet sys-kernel/installkernel sys-kernel/dracut || return 1
}

kernel_install_firmware() {
    [[ $CFG_FIRMWARE == yes ]] || return 0
    chroot_run "$(T 'Installing linux-firmware')" \
        emerge --ask=n --quiet sys-kernel/linux-firmware || return 1
}

kernel_install_microcode() {
    local mode=$CFG_MICROCODE package=""
    if [[ $mode == auto ]]; then
        mode=$(kernel_cpu_vendor)
    fi
    case "$mode" in
        intel) package=sys-firmware/intel-microcode ;;
        amd) package=sys-firmware/amd-ucode ;;
        none|unknown)
            log_info "microcode package not selected (mode=$mode)"
            return 0
            ;;
        *)
            warn "$(T 'unknown microcode mode: %s' "$mode")"
            return 0
            ;;
    esac
    chroot_run "$(T 'Installing microcode (%s)' "$mode")" emerge --ask=n --quiet "$package" || return 1
}

kernel_verify() {
    local kernels initrds kver
    kernels=$(find "$GI_ROOT/boot" -maxdepth 1 -type f \
        \( -name 'vmlinuz-*' -o -name 'kernel-*' \) -printf '%f\n' 2>/dev/null | sort || true)
    if [[ -z $kernels ]]; then
        ui_error "$(T 'Kernel is not installed')" "$(T 'Neither vmlinuz-* nor kernel-* was found in %s/boot.' "$GI_ROOT")"
        return 1
    fi
    initrds=$(find "$GI_ROOT/boot" -maxdepth 1 -type f \
        \( -name 'initrd-*' -o -name 'initramfs-*' -o -name 'initrd.img-*' \) -printf '%f\n' 2>/dev/null | sort || true)
    if [[ -z $initrds ]]; then
        warn "$(T 'initramfs not found; trying to generate one with dracut')"
        kver=$(find "$GI_ROOT/lib/modules" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' 2>/dev/null |
            sort -V | tail -n 1 || true)
        if [[ -z $kver ]]; then
            ui_error "$(T 'No kernel modules')" "$(T 'The directory %s/lib/modules is empty.' "$GI_ROOT")"
            return 1
        fi
        chroot_run "$(T 'Generating initramfs for %s' "$kver")" dracut --force --kver "$kver" || return 1
        initrds=$(find "$GI_ROOT/boot" -maxdepth 1 -type f \
            \( -name 'initrd-*' -o -name 'initramfs-*' \) -printf '%f\n' 2>/dev/null | sort || true)
        if [[ -z $initrds ]]; then
            ui_error "$(T 'initramfs was not created')" "$(T 'dracut exited successfully, but no initramfs file was found.')"
            return 1
        fi
    fi
    log_info "kernel files: $(printf '%s\n' "$kernels" | tr '\n' ' ')"
    log_info "initramfs files: $(printf '%s\n' "$initrds" | tr '\n' ' ')"
    return 0
}

